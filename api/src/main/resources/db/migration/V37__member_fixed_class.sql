-- Clases fijas por socio (2026-10-12): el admin deja precargada una clase semanal (día + hora +
-- nombre = un bloque) para un socio y el sistema le reserva sola cada fecha del período de su plan,
-- también al renovar. Ver docs/plans/2026-10-12-clases-fijas.md.
--
-- FKs en cascada: alineado con el borrado real de socios/bloques/gyms del resto del esquema
-- (si se borra el socio, el bloque o el gimnasio, la clase fija se va con ellos).
CREATE TABLE member_fixed_class (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id BIGINT NOT NULL REFERENCES gym (id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    gym_block_id BIGINT NOT NULL REFERENCES gym_block (id) ON DELETE CASCADE,
    created_by_user_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_member_fixed_class UNIQUE (member_id, gym_block_id)
);

CREATE INDEX idx_member_fixed_class_gym ON member_fixed_class (gym_id);

-- Marca de origen de la reserva: sirve para la etiqueta "Fija", para saber qué reservas futuras
-- cancelar al quitar una clase fija y para no volver a crear una fecha que el socio soltó a
-- propósito. SET NULL: si la clase fija se borra, la reserva queda como una normal (historial).
ALTER TABLE reservation ADD COLUMN fixed_class_id BIGINT REFERENCES member_fixed_class (id) ON DELETE SET NULL;

-- Índices de las FK (Postgres no los crea solo): sin ellos, borrar un bloque recorre toda
-- member_fixed_class, y quitar una clase fija (ON DELETE SET NULL de arriba) o borrar un socio
-- recorre TODA la tabla reservation para buscar sus reservas. Parcial: la mayoría de las
-- reservas no viene de una clase fija, así que el índice queda chico.
CREATE INDEX idx_member_fixed_class_block ON member_fixed_class (gym_block_id);
CREATE INDEX idx_reservation_fixed_class ON reservation (fixed_class_id) WHERE fixed_class_id IS NOT NULL;
