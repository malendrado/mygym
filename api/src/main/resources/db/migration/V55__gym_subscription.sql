-- 2) Suscripcion de un gimnasio (una fila por gimnasio).
CREATE TABLE gym_subscription (
    gym_id BIGINT PRIMARY KEY,
    plan_id BIGINT,
    -- Precio neto propio de este gimnasio (Escala a medida u oferta). NULL = el del plan.
    price_override_clp INTEGER,
    -- Cupo de socios propio. NULL = el del plan.
    max_users_override INTEGER,
    -- Fecha de inicio: define el dia de corte de cada mes. NULL mientras el gimnasio no se activa.
    anchor_date DATE,
    -- Meses seguidos cubiertos desde anchor_date. El vencimiento es anchor_date + paid_periods meses.
    paid_periods INTEGER NOT NULL DEFAULT 0,
    pending_plan_id BIGINT,
    pending_price_override_clp INTEGER,
    -- Primer dia de corte desde el que rige el plan pendiente.
    pending_plan_from DATE,
    exempt BOOLEAN NOT NULL DEFAULT FALSE,
    -- NOT_STARTED | ACTIVE | GRACE | SUSPENDED | EXEMPT. Lo recalcula el cron y cada pago.
    billing_status VARCHAR(20) NOT NULL DEFAULT 'NOT_STARTED',
    suspended_at TIMESTAMPTZ,
    -- Datos para emitir la factura.
    billing_rut VARCHAR(20),
    billing_name VARCHAR(160),
    billing_giro VARCHAR(160),
    billing_address VARCHAR(240),
    billing_email VARCHAR(160),
    -- Ultimo dia en que se envio un aviso de cobro (evita repetir el mismo dia).
    last_notice_on DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_gym_subscription_gym FOREIGN KEY (gym_id) REFERENCES gym (id) ON DELETE CASCADE,
    CONSTRAINT fk_gym_subscription_plan FOREIGN KEY (plan_id) REFERENCES mygym_plan (id),
    CONSTRAINT fk_gym_subscription_pending_plan FOREIGN KEY (pending_plan_id) REFERENCES mygym_plan (id),
    CONSTRAINT ck_gym_subscription_status CHECK (billing_status IN ('NOT_STARTED', 'ACTIVE', 'GRACE', 'SUSPENDED', 'EXEMPT')),
    CONSTRAINT ck_gym_subscription_periods CHECK (paid_periods >= 0)
);

CREATE INDEX idx_gym_subscription_plan ON gym_subscription (plan_id);

-- 3) Pagos del gimnasio a mygym (Flow, transferencia o marcados a mano por el super admin).
CREATE TABLE gym_subscription_payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id BIGINT NOT NULL,
    -- FLOW | TRANSFER | MANUAL
    method VARCHAR(12) NOT NULL,
    -- PENDING (Flow sin confirmar) | REPORTED (aviso "ya transferi") | PAID | REJECTED | VOIDED
    status VARCHAR(12) NOT NULL,
    net_clp INTEGER NOT NULL DEFAULT 0,
    iva_clp INTEGER NOT NULL DEFAULT 0,
    flow_fee_clp INTEGER NOT NULL DEFAULT 0,
    -- Lo que paga el gimnasio en total (neto + IVA + comision de Flow si fue por Flow).
    amount_clp INTEGER NOT NULL DEFAULT 0,
    period_start DATE,
    period_end DATE,
    commerce_order VARCHAR(60),
    flow_token VARCHAR(80),
    flow_order VARCHAR(40),
    transfer_date DATE,
    transfer_bank VARCHAR(80),
    transfer_operation VARCHAR(60),
    reported_by BIGINT,
    reported_at TIMESTAMPTZ,
    confirmed_by BIGINT,
    confirmed_at TIMESTAMPTZ,
    note VARCHAR(240),
    -- Estado de la suscripcion ANTES de aplicar este pago: permite anularlo y volver exacto.
    prev_anchor_date DATE,
    prev_paid_periods INTEGER,
    voided_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_gym_subscription_payment_gym FOREIGN KEY (gym_id) REFERENCES gym (id) ON DELETE CASCADE,
    CONSTRAINT ck_gym_subscription_payment_method CHECK (method IN ('FLOW', 'TRANSFER', 'MANUAL')),
    CONSTRAINT ck_gym_subscription_payment_status CHECK (status IN ('PENDING', 'REPORTED', 'PAID', 'REJECTED', 'VOIDED'))
);

CREATE INDEX idx_gym_subscription_payment_gym ON gym_subscription_payment (gym_id, created_at DESC);
CREATE UNIQUE INDEX uk_gym_subscription_payment_flow_token ON gym_subscription_payment (flow_token) WHERE flow_token IS NOT NULL;

-- 4) Periodos de suspension por no pago (auditoria).
CREATE TABLE gym_suspension (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id BIGINT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    reason VARCHAR(12) NOT NULL DEFAULT 'BILLING',
    CONSTRAINT fk_gym_suspension_gym FOREIGN KEY (gym_id) REFERENCES gym (id) ON DELETE CASCADE
);

CREATE INDEX idx_gym_suspension_gym ON gym_suspension (gym_id, started_at DESC);

