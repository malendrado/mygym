-- 1) Catalogo de planes de mygym: alimenta la landing, el FAQ y la asignacion de plan a cada gimnasio.
CREATE TABLE mygym_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL,
    name VARCHAR(60) NOT NULL,
    -- Texto corto bajo el nombre ("Hasta 100 socios").
    clients_label VARCHAR(80) NOT NULL,
    -- Precio neto mensual en CLP, sin IVA. NULL = "A medida" (se fija por gimnasio).
    price_clp INTEGER,
    -- Cupo de socios que fija el plan. NULL = sin tope propio (se define por gimnasio).
    max_users INTEGER,
    max_profesores INTEGER NOT NULL DEFAULT 10,
    max_admins INTEGER NOT NULL DEFAULT 5,
    -- Lineas de la tarjeta de precios, una por linea.
    features TEXT NOT NULL DEFAULT '',
    highlighted BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_mygym_plan_code UNIQUE (code),
    CONSTRAINT ck_mygym_plan_price CHECK (price_clp IS NULL OR price_clp > 0),
    CONSTRAINT ck_mygym_plan_max_users CHECK (max_users IS NULL OR max_users > 0)
);

