-- Firma electronica del contrato de servicios por el administrador del gimnasio (Ley 19.799, firma simple con codigo al correo).
-- Plan: docs/plans/2026-10-21-firma-contrato.md

-- 1) Respaldo de cada aceptacion. SIN clave foranea al gimnasio: la constancia debe sobrevivir a la desvinculacion del gimnasio.
CREATE TABLE gym_contract_acceptance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id BIGINT NOT NULL,
    contract_version VARCHAR(20) NOT NULL,
    -- Texto exacto que vio el firmante (con sus datos rellenados) y su huella SHA-256 en hexadecimal.
    rendered_text TEXT NOT NULL,
    rendered_sha256 VARCHAR(64) NOT NULL,
    signer_user_id BIGINT NOT NULL,
    signer_email VARCHAR(160) NOT NULL,
    signer_name VARCHAR(120) NOT NULL,
    signer_rut VARCHAR(20) NOT NULL,
    -- PERSON_OWNER = titular persona natural; LEGAL_REP = representante legal; ATTORNEY = apoderado.
    signer_capacity VARCHAR(20) NOT NULL,
    adult_declared BOOLEAN NOT NULL,
    powers_declared BOOLEAN NOT NULL,
    -- Datos del gimnasio y del plan al momento de firmar.
    gym_name VARCHAR(160) NOT NULL,
    gym_rut VARCHAR(20) NOT NULL,
    billing_kind VARCHAR(10) NOT NULL,
    plan_code VARCHAR(40) NOT NULL,
    net_price_clp INTEGER NOT NULL,
    code_sent_at TIMESTAMPTZ NOT NULL,
    signed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ip VARCHAR(64),
    user_agent VARCHAR(500),
    CONSTRAINT ck_gym_contract_acceptance_capacity CHECK (signer_capacity IN ('PERSON_OWNER', 'LEGAL_REP', 'ATTORNEY')),
    CONSTRAINT ck_gym_contract_acceptance_declared CHECK (adult_declared AND powers_declared)
);

CREATE INDEX idx_gym_contract_acceptance_gym ON gym_contract_acceptance (gym_id, contract_version);

-- La constancia no se edita ni se borra, ni siquiera desde la base.
CREATE FUNCTION gym_contract_acceptance_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'gym_contract_acceptance es de solo escritura: no se puede modificar ni borrar';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_gym_contract_acceptance_immutable
    BEFORE UPDATE OR DELETE ON gym_contract_acceptance
    FOR EACH ROW EXECUTE FUNCTION gym_contract_acceptance_immutable();

ALTER TABLE gym_contract_acceptance ENABLE ROW LEVEL SECURITY;

-- 2) Codigos de un solo uso enviados al correo del firmante. Se guarda solo el hash y los datos que declaro al pedirlo.
CREATE TABLE gym_contract_code (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gym_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    code_hash VARCHAR(100) NOT NULL,
    -- Huella del texto para el que se pidio el codigo: si el texto cambia antes de firmar, el codigo ya no sirve.
    rendered_sha256 VARCHAR(64) NOT NULL,
    signer_name VARCHAR(120) NOT NULL,
    signer_rut VARCHAR(20) NOT NULL,
    signer_capacity VARCHAR(20) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_gym_contract_code_gym FOREIGN KEY (gym_id) REFERENCES gym (id) ON DELETE CASCADE
);

-- Cuenta de envios por usuario y busqueda del ultimo codigo vigente.
CREATE INDEX idx_gym_contract_code_user ON gym_contract_code (user_id, created_at);
CREATE INDEX idx_gym_contract_code_gym ON gym_contract_code (gym_id);

ALTER TABLE gym_contract_code ENABLE ROW LEVEL SECURITY;
